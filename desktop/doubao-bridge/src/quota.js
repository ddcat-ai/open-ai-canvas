'use strict';
/* 额度耗尽判定（统一口径，2026-11-10）
 *
 * 豆包把「额度耗尽」当普通文本回复：不报错、不出图、视频也不推送。若只在轮询超时后
 * 才判定，一次额度耗尽要白等满 150s（生图）/120s（文本）/20min（视频），期间还占着
 * 账号串行队列，让 accounts 的「自动换号」迟迟不触发（19:23/19:50/19:57 三次实证：
 * 三次都报「生图超时」，账号却始终没被标记额度耗尽，后续任务继续派给同一个死账号）。
 *
 * 收敛到单一来源：driver 轮询中命中即快速失败，错误文案含「额度已用完」——
 * accounts.onTaskDone 用它做换号口径（/额度已用完/）。
 * 注意「本次生成将消耗每日免费额度」这类受理回执不含下面任何一个词，不会误判。
 */
const QUOTA_TEXT_RE = /额度.{0,6}(用完|耗尽)|今日.{0,8}次数已用完|次数不足|额度不足|开通订阅/;

function isQuotaText(text) {
  return QUOTA_TEXT_RE.test(String(text || ''));
}

module.exports = { QUOTA_TEXT_RE, isQuotaText };
