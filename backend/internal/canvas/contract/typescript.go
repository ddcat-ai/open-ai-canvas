	for _, typ := range []reflect.Type{reflect.TypeOf(Options{}), reflect.TypeOf(ReferenceBinding{}), reflect.TypeOf(GenerationSpec{})} {
		fmt.Fprintf(&out, "export type %s = {\n", typ.Name())
		for i := 0; i < typ.NumField(); i++ {
			field := typ.Field(i)
			parts := strings.Split(field.Tag.Get("json"), ",")
			optional := ""
			if len(parts) > 1 && parts[1] == "omitempty" {
				optional = "?"
			}
			valueType := tsType(field.Type)
			if values := field.Tag.Get("enum"); values != "" {
				quoted := []string{}
				for _, value := range strings.Split(values, ",") {
					quoted = append(quoted, fmt.Sprintf("%q", value))
				}
				valueType = strings.Join(quoted, " | ")
			}
			fmt.Fprintf(&out, "    %s%s: %s;\n", parts[0], optional, valueType)
		}
		out.WriteString("};\n\n")
	}
	fields := []map[string]any{}
