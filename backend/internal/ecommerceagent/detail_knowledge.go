func DetailPlanningKnowledge(platform string, count int) string {
	platform = strings.TrimSpace(platform)
	if platform == "" {
		platform = "用户尚未指定；按通用商品详情页规范策划"
	}
	if count < 1 {
		count = 9
	}
	// The source list documents where the method comes from; the model does not
	// need its 2,500 characters of URLs to plan a page.
	method := strings.TrimSpace(strings.Split(EcommerceDetailKnowledge, "【知识来源与适用范围】")[0])
	return method + "\n" + PremiumDetailLayoutKnowledge + "\n【本轮应用】目标平台：" + platform + "；详情页张数：" + strconv.Itoa(count) + "。平台主图/附图要求按该平台与地区适配；上述九张节奏只在九张模式生效。"
}
